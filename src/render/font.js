const ACCENTED = Object.freeze({
  á: ['a', 'acute'], é: ['e', 'acute'], í: ['i', 'acute'], ó: ['o', 'acute'], ú: ['u', 'acute'],
  ü: ['u', 'diaeresis'], ñ: ['n', 'tilde'],
  Á: ['A', 'acute'], É: ['E', 'acute'], Í: ['I', 'acute'], Ó: ['O', 'acute'], Ú: ['U', 'acute'],
  Ü: ['U', 'diaeresis'], Ñ: ['N', 'tilde'],
});

// Marks as [x, y] pixels, two rows tall at most.
const MARKS = Object.freeze({
  acute: [[3, 0], [2, 1]],
  diaeresis: [[1, 0], [3, 0]],
  tilde: [[1, 0], [2, 0], [0, 1], [3, 1], [4, 1]],
});

const ASCII = Array.from({ length: COLUMNS.length }, (_, i) => String.fromCharCode(FIRST + i)).join('');
const SUPPORTED_CHARS = `${ASCII}${Object.keys(ACCENTED).join('')}¡¿`;

const isUpper = (ch) => ch >= 'A' && ch <= 'Z';
const columnsFor = (ch) => COLUMNS[ch.charCodeAt(0) - FIRST] || COLUMNS['?'.charCodeAt(0) - FIRST];

// Mirrors a glyph top to bottom (bit y goes to bit 6 - y): '!' becomes the inverted mark.
const flipRows = (cols) =>
  cols.map((bits) => [0, 1, 2, 3, 4, 5, 6].reduce((acc, y) => acc | (((bits >> y) & 1) << (6 - y)), 0));

const bodyPixels = (cols) =>
  cols.flatMap((bits, x) =>
    [0, 1, 2, 3, 4, 5, 6].filter((y) => (bits >> y) & 1).map((y) => [x, y + TOP]));

function buildPixels(ch) {
  if (ch === '¡') return bodyPixels(flipRows(columnsFor('!')));
  if (ch === '¿') return bodyPixels(flipRows(columnsFor('?')));
  const accented = ACCENTED[ch];
  if (!accented) return bodyPixels(columnsFor(ch));
  const [base, mark] = accented;
  const body = bodyPixels(columnsFor(base)).filter(([, y]) => !(base === 'i' && y === TOP));
  const offset = isUpper(base) ? 0 : 1;
  return [...body, ...MARKS[mark].map(([x, y]) => [x, y + offset])];
}

// Memoized: each glyph is built once and then reused every frame.
const cache = new Map();
function pixelsOf(ch) {
  if (!cache.has(ch)) cache.set(ch, Object.freeze(buildPixels(ch)));
  return cache.get(ch);
}

const textWidth = (text, scale = 1) => text.length * CELL_W * scale;

module.exports = { CELL_W, CELL_H, LINE_H, SUPPORTED_CHARS, pixelsOf, textWidth };
